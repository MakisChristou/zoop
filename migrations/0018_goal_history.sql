-- Keep the legacy current-goal API while giving every cut a permanent identity.
ALTER TABLE weight_goals ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE;
CREATE TABLE weight_goal_history (
 id bigint PRIMARY KEY,
 device_id text NOT NULL REFERENCES devices(id),
 started_at timestamptz NOT NULL,
 ended_at timestamptz NOT NULL,
 end_reason text NOT NULL CHECK (end_reason IN ('manual','scheduled','legacy')),
 settings jsonb NOT NULL,
 target_weight_kg double precision,
 CHECK (ended_at >= started_at)
);
CREATE INDEX weight_goal_history_device_started ON weight_goal_history(device_id,started_at DESC,id DESC);

-- Freeze the intended target at closure. Actual progress can still reflect corrected
-- observations inside the period. Start-day readings are shared calendar context;
-- readings at/after the actual end boundary cannot extend a closed cut.
CREATE FUNCTION closed_goal_target(device text, settings jsonb, ended timestamptz)
RETURNS double precision LANGUAGE sql STABLE AS $$
 WITH baseline AS (
  SELECT kg FROM weight_readings
  WHERE device_id=device AND NOT removed AND kg BETWEEN 20 AND 400
   AND measured_at < ended
   AND measured_at >= (((settings->>'started_at')::timestamptz AT TIME ZONE (settings->>'timezone'))::date::timestamp AT TIME ZONE (settings->>'timezone'))
  ORDER BY (measured_at AT TIME ZONE (settings->>'timezone'))::date,
    (source='health') DESC, measured_at DESC, id DESC LIMIT 1
 ), target AS (
  SELECT kg - (settings->>'weekly_loss_kg')::double precision *
    ((settings->>'finish_date')::date - ((settings->>'started_at')::timestamptz AT TIME ZONE (settings->>'timezone'))::date) / 7.0 AS kg
  FROM baseline
 )
 SELECT kg FROM target WHERE kg BETWEEN 20 AND 400
$$;

-- Recover only actual start boundaries, not every settings revision.
WITH revisions AS (
 SELECT device_id, (settings->>'started_at')::timestamptz AS start,
        settings, revision,
        bool_or((settings->>'active')::boolean) OVER (PARTITION BY device_id,settings->>'started_at') AS was_active
 FROM weight_goal_revisions
), latest AS (
 SELECT DISTINCT ON (device_id,start) * FROM revisions WHERE was_active
 ORDER BY device_id,start,revision DESC
), periods AS (
 SELECT *,lead(start) OVER (PARTITION BY device_id ORDER BY start) AS next_start FROM latest
), closed AS (
 SELECT p.*,w.id AS current_id,w.started_at AS current_start,
   CASE WHEN NOT (p.settings->>'active')::boolean THEN (p.settings->>'updated_at')::timestamptz
        ELSE p.next_start END AS actual_end
 FROM periods p JOIN weight_goals w USING(device_id)
 WHERE NOT (p.settings->>'active')::boolean OR p.start <> w.started_at
), identified AS (
 SELECT *,CASE WHEN start=current_start THEN current_id
    ELSE nextval(pg_get_serial_sequence('weight_goals','id')) END AS period_id
 FROM closed WHERE actual_end IS NOT NULL AND actual_end>=start
)
INSERT INTO weight_goal_history
 SELECT period_id,device_id,start,actual_end,'legacy',
        settings || jsonb_build_object('id',period_id),
        closed_goal_target(device_id,settings,actual_end)
 FROM identified;

CREATE FUNCTION preserve_weight_goal_period() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.started_at <> OLD.started_at THEN
  NEW.id := nextval(pg_get_serial_sequence('weight_goals','id'));
 END IF;
 IF OLD.active AND NOT NEW.active THEN
  INSERT INTO weight_goal_history(id,device_id,started_at,ended_at,end_reason,settings,target_weight_kg)
  VALUES (OLD.id,OLD.device_id,OLD.started_at,NEW.updated_at,
   CASE WHEN OLD.finish_date IS NOT NULL AND
    NEW.updated_at >= ((OLD.finish_date+1)::timestamp AT TIME ZONE OLD.timezone)
    THEN 'scheduled' ELSE 'manual' END,
   to_jsonb(OLD),closed_goal_target(OLD.device_id,to_jsonb(OLD),NEW.updated_at))
  ON CONFLICT(id) DO NOTHING;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER weight_goal_period BEFORE UPDATE ON weight_goals
FOR EACH ROW EXECUTE FUNCTION preserve_weight_goal_period();
