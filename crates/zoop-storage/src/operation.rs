use std::fmt;

/// What the store was doing when it failed. Rendered into every `StorageError`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StoreOperation {
    Sharing,
    Accounts,
    HealthSync,
    Analysis,
    MorningInsights,
    Recovery,
    Progress,
    CorrectWorkout,
    Connect,
    Migrate,
    Ping,
    UpsertDevice,
    InsertRawFrame,
    FetchPendingFrames,
    MarkFrameDecoded,
    UpsertSample,
    InsertEvent,
    InsertEcgStrip,
    LatestSample,
    SamplesInRange,
    ListDevices,
    UpsertSleep,
    ListSleeps,
    ListDays,
    LocalDay,
    HourlySteps,
    SleepWindows,
    RestingHr,
    ObservedHrMax,
    ReplaceWorkouts,
    ListWorkouts,
    UpsertLabel,
    UpsertStrain,
    GetProfile,
    UpsertProfile,
    ProfilePhoto,
}

impl fmt::Display for StoreOperation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let name = match self {
            Self::Sharing => "shared dashboards",
            Self::Accounts => "account access",
            Self::CorrectWorkout => "correct workout",
            Self::Progress => "read progress",
            Self::Recovery => "record recovery observation",
            Self::MorningInsights => "read morning insights",
            Self::HealthSync => "synchronize health records",
            Self::Analysis => "process analysis work",
            Self::Connect => "connect",
            Self::Migrate => "migrate",
            Self::Ping => "ping",
            Self::UpsertDevice => "upsert device",
            Self::InsertRawFrame => "insert raw frame",
            Self::FetchPendingFrames => "fetch pending frames",
            Self::MarkFrameDecoded => "mark frame decoded",
            Self::UpsertSample => "upsert sample",
            Self::InsertEvent => "insert event",
            Self::InsertEcgStrip => "insert ECG strip",
            Self::LatestSample => "read latest sample",
            Self::SamplesInRange => "read samples in range",
            Self::ListDevices => "list devices",
            Self::UpsertSleep => "upsert sleep",
            Self::ListSleeps => "list sleeps",
            Self::ListDays => "list days",
            Self::LocalDay => "resolve local day",
            Self::HourlySteps => "read hourly steps",
            Self::SleepWindows => "read sleep windows",
            Self::RestingHr => "read resting heart rate",
            Self::ObservedHrMax => "read observed maximal heart rate",
            Self::ReplaceWorkouts => "replace workouts",
            Self::ListWorkouts => "list workouts",
            Self::UpsertLabel => "upsert workout label",
            Self::UpsertStrain => "upsert strain",
            Self::GetProfile => "read profile",
            Self::UpsertProfile => "upsert profile",
            Self::ProfilePhoto => "store profile photo",
        };
        f.write_str(name)
    }
}
